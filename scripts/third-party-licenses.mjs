// Walks the dependency graph of everything we ship (web app, MCP server, Electron) and writes
// THIRD_PARTY_NOTICES.md. Run: node scripts/third-party-licenses.mjs
import { readFileSync, realpathSync, existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
const root = new URL("..", import.meta.url).pathname;
const seen = new Map();
function pkgDir(name, from) {
  let dir = from;
  for (;;) {
    const p = join(dir, "node_modules", name, "package.json");
    if (existsSync(p)) return dirname(realpathSync(p));
    const up = dirname(dir);
    if (up === dir) return null;
    dir = up;
  }
}
function walk(dir, includeDev = []) {
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) return;
  seen.set(key, { name: pkg.name, version: pkg.version, license: typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? (pkg.licenses ? JSON.stringify(pkg.licenses) : "UNKNOWN") });
  const deps = { ...pkg.dependencies, ...pkg.optionalDependencies, ...Object.fromEntries(includeDev.map((d) => [d, "*"])) };
  for (const name of Object.keys(deps)) {
    const d = pkgDir(name, dir);
    if (d) walk(d);
  }
}
walk(join(root, "apps/web"));
walk(join(root, "packages/mcp"), ["@meercad/ai"]);
walk(join(root, "apps/desktop"), ["electron"]);
const rows = [...seen.values()].filter((p) => !p.name.startsWith("@meercad/") && p.name !== "meercad-desktop").sort((a, b) => a.name.localeCompare(b.name));
const copyleft = rows.filter((p) => /GPL/.test(p.license));
const blocked = rows.filter((p) => /(^|[^L])GPL|AGPL|SSPL|BUSL|NC|UNKNOWN/i.test(p.license) && !/LGPL/.test(p.license));
const out = `# Third-party software in meerCAD

meerCAD itself is licensed under the Functional Source License 1.1 (FSL-1.1-ALv2, see LICENSE); the packages \`@meercad/schema\`, \`@meercad/io\` and \`@meercad/naming\` are MIT.
The distributed app contains the following third-party components. Generated by \`node scripts/third-party-licenses.mjs\`.

## LGPL components

These are used unmodified as separate WebAssembly modules that are loaded at runtime. In the macOS app they live
as plain files under \`meerCAD.app/Contents/Resources/web/assets/\` and can be replaced with your own build.
The license text is in \`licenses/LGPL-2.1.txt\`.

- **Open CASCADE Technology (OCCT)** — geometry kernel, LGPL-2.1 with the OCCT exception. Source: https://github.com/Open-Cascade-SAS/OCCT
  WebAssembly build \`replicad-opencascadejs\` (${copyleft.find((p) => p.name === "replicad-opencascadejs")?.version ?? ""}): https://github.com/sgenoud/replicad
- **PlaneGCS** — 2D constraint solver from FreeCAD, LGPL-2.1+. Source: https://github.com/FreeCAD/FreeCAD (src/Mod/Sketcher/App/planegcs)
  WebAssembly build \`@salusoft89/planegcs\` (${copyleft.find((p) => p.name === "@salusoft89/planegcs")?.version ?? ""}): https://github.com/Salusoft89/planegcs

Electron additionally ships Chromium's licenses in \`LICENSES.chromium.html\` inside the app bundle.

## All components

| Package | Version | License |
|---|---|---|
${rows.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`).join("\n")}
`;
writeFileSync(new URL("../THIRD_PARTY_NOTICES.md", import.meta.url), out);
console.log(`${rows.length} packages, ${copyleft.length} LGPL; problematic: ${blocked.map((p) => p.name).join(", ") || "none"}`);
if (blocked.length) process.exit(1);
