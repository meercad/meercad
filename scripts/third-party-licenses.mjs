// The full licence text of every component (their copyright notices must travel with the app),
// shown in the app's Licences page and shipped next to the Mac app.
const licenceFile = (dir) => readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
const texts = rows.map((p) => {
  const f = licenceFile(p.dir);
  const text = f ? readFileSync(join(p.dir, f), "utf8").trim() : `${p.license} (the package ships no licence file)`;
  return `${"=".repeat(78)}\n${p.name} ${p.version} (${p.license})\n${"=".repeat(78)}\n\n${text}\n`;
});
const full = `Licence texts of the third-party components in meerCAD (see THIRD_PARTY_NOTICES.md).\nGenerated by \`node scripts/third-party-licenses.mjs\`.\n\n${texts.join("\n")}`;

const file = new URL("../THIRD_PARTY_NOTICES.md", import.meta.url);
const fullFile = new URL("../licenses/THIRD_PARTY_LICENSES.txt", import.meta.url);
const stale = readFileSync(file, "utf8") !== out || !existsSync(fullFile) || readFileSync(fullFile, "utf8") !== full;
if (!check) {
  writeFileSync(file, out);
  writeFileSync(fullFile, full);
} else if (stale) console.error("THIRD_PARTY_NOTICES.md or licenses/THIRD_PARTY_LICENSES.txt is out of date: run node scripts/third-party-licenses.mjs");
const missing = rows.filter((p) => !licenceFile(p.dir));
if (missing.length) console.log(`no licence file in: ${missing.map((p) => p.name).join(", ")}`);
console.log(`${rows.length} packages, ${copyleft.length} LGPL; problematic: ${blocked.map((p) => p.name).join(", ") || "none"}`);
if (blocked.length || (check && stale)) process.exit(1);
