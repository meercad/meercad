// Walks the dependency graph of everything we ship (web app, MCP server, Electron) and writes
// THIRD_PARTY_NOTICES.md. Run: node scripts/third-party-licenses.mjs
// With --check (CI) it writes nothing and fails when the file is out of date or a dependency's
// license is not allowed: GPL, AGPL, LGPL-3 and non-commercial licenses would rule out the App Store.
import { readFileSync, readdirSync, realpathSync, existsSync, writeFileSync } from "node:fs";
const check = process.argv.includes("--check");
import { dirname, join } from "node:path";
const root = new URL("..", import.meta.url).pathname;
const seen = new Map();
function pkgDir(name, from) {
  let dir = from;
  for (;;) {
    const p = join(dir, "node_modules", name, "package.json");
    if (existsSync(p)) return dirname(realpathSync(p));
    const up = dirname(dir);
    if (up === dir) return null;
    dir = up;
  }
}
function walk(dir, includeDev = []) {
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) return;
  seen.set(key, { name: pkg.name, version: pkg.version, dir, license: typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? (pkg.licenses ? JSON.stringify(pkg.licenses) : "UNKNOWN") });
  const deps = { ...pkg.dependencies, ...pkg.optionalDependencies, ...Object.fromEntries(includeDev.map((d) => [d, "*"])) };
  for (const name of Object.keys(deps)) {
    const d = pkgDir(name, dir);
    if (d) walk(d);
  }
}
walk(join(root, "apps/web"));
walk(join(root, "packages/mcp"), ["@meercad/ai"]);
walk(join(root, "apps/desktop"), ["electron"]);
walk(join(root, "apps/ios"));
const rows = [...seen.values()].filter((p) => !p.name.startsWith("@meercad/") && p.name !== "meercad-desktop" && p.name !== "meercad-ios").sort((a, b) => a.name.localeCompare(b.name));
const copyleft = rows.filter((p) => /GPL/.test(p.license));
const blocked = rows.filter((p) => (/(^|[^L])GPL|AGPL|SSPL|BUSL|NC|UNKNOWN/i.test(p.license) && !/LGPL/.test(p.license)) || /LGPL-3/.test(p.license));
