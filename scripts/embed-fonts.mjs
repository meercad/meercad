#!/usr/bin/env node
/**
 * Embeds the fonts for text steps into the kernel as base64 (the kernel runs in a worker, in Node
 * for tests and on iOS, so it cannot load files by URL). Latin subsets of Roboto and Roboto Mono
 * (SIL Open Font License 1.1) from @fontsource.
 *
 *   node scripts/embed-fonts.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const files = join(root, "packages/kernel/node_modules/@fontsource");
const fonts = {
  sans: "roboto/files/roboto-latin-400-normal.woff",
  "sans-bold": "roboto/files/roboto-latin-700-normal.woff",
  mono: "roboto-mono/files/roboto-mono-latin-400-normal.woff",
};
const lines = Object.entries(fonts).map(
  ([name, file]) => `  ${JSON.stringify(name)}: "${readFileSync(join(files, file)).toString("base64")}",`,
);
writeFileSync(
  join(root, "packages/kernel/src/fonts.generated.ts"),
  `// Generated by scripts/embed-fonts.mjs: Roboto and Roboto Mono (latin), SIL Open Font License 1.1.\nexport const FONTS: Record<"sans" | "sans-bold" | "mono", string> = {\n${lines.join("\n")}\n};\n`,
);
console.log("✓ packages/kernel/src/fonts.generated.ts");
